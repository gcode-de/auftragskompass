-- PRODUCTS-DELETE-01: a deleted product is recorded as its own audit action.
-- Additive constraint replacement in the established 0052 pattern: the action
-- list only grows, and every existing action keeps its meaning.
ALTER TABLE audit_events DROP CONSTRAINT audit_events_action_check;
